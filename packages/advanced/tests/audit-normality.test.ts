import assert from 'node:assert/strict'
import { it } from 'vitest'
import { andersonDarling, shapiroWilk } from '../src/normality.js'

it('F02: extreme non-normality has a saturated small tail, never p=1', () => {
  const result = andersonDarling([...Array(1000).fill(0), ...Array(1000).fill(1)])
  assert.ok(Math.abs(result.statistic - 359.1174372976775) < 1e-8)
  assert.equal(result.pValue, 0)
})

it('F02: retains the validated moderate-tail approximation', () => {
  const result = andersonDarling([...Array(10).fill(0), ...Array(10).fill(1)])
  assert.ok(Math.abs(result.statistic - 3.4312722970674656) < 1e-10)
  assert.ok(result.pValue >= 0 && result.pValue < 1e-7)
})

it('F02: monotonic two-point samples never turn the tail upwards', () => {
  let previous = 1
  for (const half of [4, 8, 10, 20, 35, 36, 37, 40, 100, 500, 1000, 2000]) {
    const result = andersonDarling([...Array(half).fill(0), ...Array(half).fill(1)])
    assert.ok(result.pValue <= previous, `tail increased at n=${half * 2}`)
    assert.ok(Number.isFinite(result.pValue) && result.pValue >= 0)
    previous = result.pValue
  }
})

for (const shift of [0, 1e9, 1e12, 1e15, -1e15]) {
  it(`F06: Shapiro-Wilk agrees with SciPy after an exactly representable shift (${shift})`, () => {
    const sample = [1, 2, 3, 4, 5, 6, 7, 8, 9, 18]
    const reference = shapiroWilk(sample)
    const result = shapiroWilk(sample.map((v) => v + shift))
    assert.ok(Math.abs(result.statistic - reference.statistic) < 1e-12)
    assert.ok(Math.abs(result.pValue - reference.pValue) < 1e-11)
    // scipy.stats.shapiro, audited reference sample; approximation coefficients differ slightly.
    assert.ok(Math.abs(result.pValue - 0.0847506487) < 1e-8)
    assert.ok(result.pValue > 0.05)
  })
}

for (const scale of [1e-100, 1e-10, 0.5, 2, 1e10, 1e100, -3]) {
  it(`F06: Shapiro-Wilk remains scale invariant (${scale})`, () => {
    const sample = [1, 2, 3, 4, 5, 6, 7, 8, 9, 18]
    const a = shapiroWilk(sample)
    const b = shapiroWilk(sample.map((v) => v * scale))
    assert.ok(Math.abs(a.statistic - b.statistic) < 1e-12)
    assert.ok(Math.abs(a.pValue - b.pValue) < 1e-11)
  })
}

for (const sample of [[1, 2, 3], [1, 2, 10], [1, 2, 3, 4], [0, 1, 4, 7, 9, 11, 13]]) {
  it(`F06: paired summation handles odd/even samples, n=${sample.length}, last=${sample.at(-1)}`, () => {
    const a = shapiroWilk(sample)
    const b = shapiroWilk(sample.map((v) => v + 1e12))
    assert.ok(Number.isFinite(a.statistic) && Number.isFinite(a.pValue))
    assert.ok(Math.abs(a.statistic - b.statistic) < 1e-12)
    assert.ok(Math.abs(a.pValue - b.pValue) < 1e-11)
  })
}

it('F02/F06: constant and too-short samples are still rejected', () => {
  assert.throws(() => andersonDarling(Array(20).fill(1)), /identical/)
  assert.throws(() => shapiroWilk(Array(20).fill(1)), /identical/)
  assert.throws(() => shapiroWilk([1, 2]), /at least 3/)
})

